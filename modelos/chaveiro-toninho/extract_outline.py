"""Extract Toninho's silhouette (and the green ball) from the photo.

Usage:
    python extract_outline.py <photo.png> <out_dir>

Outputs in <out_dir>:
    toninho-outline.scad  - polygon points (normalized: silhouette height = 1.0)
    mask-debug.png        - segmentation overlay for visual check
"""

import sys
from pathlib import Path

import cv2
import numpy as np

# --- Segmentation hints (pixel coords in the 472x632 source photo) ---
DOG_RECT = (30, 120, 400, 505)  # x, y, w, h: box that contains the whole dog
# The white hose in the lower-left corner touches the dog's paw: mark it as background.
HOSE_POLYLINE = [(0, 455), (60, 495), (110, 535), (145, 575), (160, 632)]
HOSE_THICKNESS = 34
# The left front paw is split by the hose; this outline (traced by hand) is forced to foreground.
LEFT_PAW_POLYGON = [
    (62, 452), (100, 444), (140, 450), (158, 500), (160, 555), (142, 582),
    (100, 580), (62, 575), (42, 556), (38, 520), (48, 480),
]
GRABCUT_ITERATIONS = 8
CONTOUR_EPSILON_PX = 1.0  # polygon simplification tolerance

# Face details picked by hand from the photo: (center_x, center_y, radius_x, radius_y)
FACE_FEATURES = {
    "left_eye": (184, 216, 11, 11),
    "right_eye": (250, 211, 10, 10),
    "nose": (233, 262, 17, 15),
}

# Green ball (HSV range)
BALL_HSV_LOW = (35, 60, 80)
BALL_HSV_HIGH = (85, 255, 255)


def largest_contour(mask: np.ndarray) -> np.ndarray:
    contours, _ = cv2.findContours(mask, cv2.RETR_EXTERNAL, cv2.CHAIN_APPROX_NONE)
    contour = max(contours, key=cv2.contourArea)
    return cv2.approxPolyDP(contour, CONTOUR_EPSILON_PX, True).reshape(-1, 2)


def main(photo: Path, out_dir: Path) -> None:
    img = cv2.imread(str(photo))

    mask = np.zeros(img.shape[:2], np.uint8)
    bgd = np.zeros((1, 65), np.float64)
    fgd = np.zeros((1, 65), np.float64)
    cv2.grabCut(img, mask, DOG_RECT, bgd, fgd, GRABCUT_ITERATIONS, cv2.GC_INIT_WITH_RECT)

    # Force the hose to background and re-run with the hint.
    cv2.polylines(mask, [np.array(HOSE_POLYLINE)], False, cv2.GC_BGD, HOSE_THICKNESS)
    cv2.grabCut(img, mask, None, bgd, fgd, GRABCUT_ITERATIONS, cv2.GC_INIT_WITH_MASK)

    dog = np.where((mask == cv2.GC_FGD) | (mask == cv2.GC_PR_FGD), 255, 0).astype(np.uint8)

    # Ball: green pixels, filled.
    hsv = cv2.cvtColor(img, cv2.COLOR_BGR2HSV)
    ball = cv2.inRange(hsv, BALL_HSV_LOW, BALL_HSV_HIGH)
    ball = cv2.morphologyEx(ball, cv2.MORPH_CLOSE, np.ones((9, 9), np.uint8))
    ball_contour = largest_contour(ball)
    (bx, by), br = cv2.minEnclosingCircle(ball_contour)

    # Ball is always part of the silhouette; fill holes and keep the biggest blob.
    cv2.circle(dog, (int(bx), int(by)), int(br), 255, -1)
    cv2.fillPoly(dog, [np.array(LEFT_PAW_POLYGON)], 255)
    dog = cv2.morphologyEx(dog, cv2.MORPH_CLOSE, np.ones((7, 7), np.uint8))
    dog = cv2.morphologyEx(dog, cv2.MORPH_OPEN, np.ones((5, 5), np.uint8))
    dog_contour = largest_contour(dog)

    x0, y0, w, h = cv2.boundingRect(dog_contour)

    def normalize(points: np.ndarray) -> list[tuple[float, float]]:
        # Flip Y (image down -> OpenSCAD up), origin at bounding-box bottom-left, height = 1.
        return [((x - x0) / h, (y0 + h - y) / h) for x, y in points]

    dog_pts = normalize(dog_contour)
    top_idx = int(np.argmin(dog_contour[:, 1]))
    top_pt = normalize(dog_contour[top_idx : top_idx + 1])[0]
    ball_center = normalize(np.array([[bx, by]]))[0]

    def fmt(points):
        return ",\n    ".join(f"[{x:.5f}, {y:.5f}]" for x, y in points)

    scad = (
        "// Generated by extract_outline.py from toninho.png - do not edit by hand.\n"
        "// Units are normalized: silhouette height = 1.0\n"
        f"outline_aspect = {w / h:.5f}; // width / height\n"
        f"outline_top = [{top_pt[0]:.5f}, {top_pt[1]:.5f}]; // highest point of the outline\n"
        f"ball_center = [{ball_center[0]:.5f}, {ball_center[1]:.5f}];\n"
        f"ball_radius = {br / h:.5f};\n"
        + "".join(
            f"{name}_center = [{normalize(np.array([[fx, fy]]))[0][0]:.5f}, "
            f"{normalize(np.array([[fx, fy]]))[0][1]:.5f}];\n"
            f"{name}_radii = [{rx / h:.5f}, {ry / h:.5f}];\n"
            for name, (fx, fy, rx, ry) in FACE_FEATURES.items()
        )
        +
        f"outline_points = [\n    {fmt(dog_pts)}\n];\n"
    )
    out_dir.mkdir(parents=True, exist_ok=True)
    (out_dir / "toninho-outline.scad").write_text(scad, encoding="utf-8")

    debug = img.copy()
    overlay = debug.copy()
    overlay[dog > 0] = (0, 0, 255)
    debug = cv2.addWeighted(overlay, 0.4, debug, 0.6, 0)
    cv2.drawContours(debug, [dog_contour.reshape(-1, 1, 2)], -1, (0, 255, 255), 2)
    cv2.circle(debug, (int(bx), int(by)), int(br), (255, 0, 0), 2)
    cv2.imwrite(str(out_dir / "mask-debug.png"), debug)

    print(f"dog points: {len(dog_pts)}, bbox {w}x{h}px, aspect {w / h:.3f}")
    print(f"ball center px ({bx:.0f},{by:.0f}) r={br:.0f}")


if __name__ == "__main__":
    main(Path(sys.argv[1]), Path(sys.argv[2]))
